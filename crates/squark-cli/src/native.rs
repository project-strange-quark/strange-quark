//! App runtimes for apps with native modules (architecture §13), and the
//! Tauri compatibility prelude.
//!
//! An app's native modules are an ordinary Rust library crate whose
//! `modules()` returns `Vec<squark_native::Module>`. `squark build` writes a
//! small binary crate under the app's `target/squark-runtime/` that passes
//! them to `squark_host::runtime_main`, builds it from a Strange Quark source
//! checkout, and uses the result as the runtime the pack is appended to.
//! Apps without native modules keep the prebuilt runtime.

use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use crate::{
    config::{RawCompatConfig, RawNativeConfig, resolve_path},
    error::CliError,
    pack::Prelude,
};

/// Which Cargo profile builds the app runtime.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RuntimeProfile {
    /// `squark build`: stripped, as the stock dist runtime.
    Dist,
    /// `squark dev`: Strange Quark's dev profile (its dependencies optimized).
    Dev,
}

impl RuntimeProfile {
    fn cargo_name(self) -> &'static str {
        match self {
            Self::Dist => "dist",
            Self::Dev => "dev",
        }
    }

    fn output_dir(self) -> &'static str {
        match self {
            Self::Dist => "dist",
            Self::Dev => "debug",
        }
    }
}

/// The Strange Quark checkout app runtimes build from.
fn squark_source(project_dir: &Path, native: &RawNativeConfig) -> Result<PathBuf, CliError> {
    let source = match (&native.squark_source, std::env::var_os("SQUARK_SOURCE_DIR")) {
        (Some(path), _) => resolve_path(project_dir, Path::new(path)),
        (None, Some(path)) => PathBuf::from(path),
        (None, None) => {
            return Err(CliError::Usage(
                "native.crate needs a Strange Quark source checkout to build the app runtime: set \
                 native.squarkSource in squark.config.ts or SQUARK_SOURCE_DIR"
                    .to_owned(),
            ));
        }
    };
    if !source.join("crates/squark-host/Cargo.toml").is_file() {
        return Err(CliError::Usage(format!(
            "{} is not a Strange Quark source checkout (no crates/squark-host)",
            source.display()
        )));
    }
    fs::canonicalize(&source).map_err(|source_error| CliError::Io {
        path: source,
        source: source_error,
    })
}

/// The `[package] name` of a crate's Cargo.toml.
fn package_name(manifest: &Path) -> Result<String, CliError> {
    let text = fs::read_to_string(manifest).map_err(|source| CliError::Io {
        path: manifest.to_path_buf(),
        source,
    })?;
    let mut in_package = false;
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            in_package = line == "[package]";
            continue;
        }
        if in_package
            && let Some(rest) = line.strip_prefix("name")
            && let Some(value) = rest.trim_start().strip_prefix('=')
        {
            let value = value.trim().trim_matches('"');
            if !value.is_empty() {
                return Ok(value.to_owned());
            }
        }
    }
    Err(CliError::Usage(format!(
        "{} has no [package] name",
        manifest.display()
    )))
}

fn toml_path(path: &Path) -> String {
    path.display()
        .to_string()
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
}

/// The generated runtime crate's manifest.
pub fn runtime_manifest(
    source: &Path,
    app_crate: &Path,
    app_package: &str,
    features: &[String],
    default_features: bool,
) -> String {
    let features = features
        .iter()
        .map(|feature| format!("\"{}\"", feature.replace(['"', '\\'], "")))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        r#"# Generated by `squark build`; do not edit.
[package]
name = "squark-app-runtime"
version = "0.0.0"
edition = "2024"
publish = false

[[bin]]
name = "squark-app-runtime"
path = "main.rs"

[dependencies]
squark-host = {{ path = "{host}" }}
squark-native = {{ path = "{native}" }}
app = {{ path = "{app}", package = "{package}", features = [{features}], default-features = {default_features} }}

[patch.crates-io]
stylo = {{ path = "{stylo}" }}

[profile.release]
lto = "thin"
codegen-units = 1
debug = "line-tables-only"

[profile.dist]
inherits = "release"
debug = false
strip = "symbols"

[profile.dev.package."*"]
opt-level = 2

[workspace]
"#,
        host = toml_path(&source.join("crates/squark-host")),
        native = toml_path(&source.join("crates/squark-native")),
        app = toml_path(app_crate),
        package = app_package.replace('"', ""),
        stylo = toml_path(&source.join("vendor/stylo")),
    )
}

pub const RUNTIME_MAIN: &str = r#"// Generated by `squark build`; do not edit.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

fn main() -> std::process::ExitCode {
    squark_host::runtime_main(Some(squark_native::dispatcher(app::modules())))
}
"#;

fn write_if_changed(path: &Path, contents: &[u8]) -> Result<(), CliError> {
    if fs::read(path).is_ok_and(|current| current == contents) {
        return Ok(());
    }
    fs::write(path, contents).map_err(|source| CliError::Io {
        path: path.to_path_buf(),
        source,
    })
}

/// Build the app runtime for `native.crate`, returning the executable.
pub fn build_native_runtime(
    project_dir: &Path,
    native: &RawNativeConfig,
    profile: RuntimeProfile,
) -> Result<Option<PathBuf>, CliError> {
    let Some(crate_dir) = &native.crate_dir else {
        return Ok(None);
    };
    let app_crate = resolve_path(project_dir, Path::new(crate_dir));
    let app_manifest = app_crate.join("Cargo.toml");
    if !app_manifest.is_file() {
        return Err(CliError::Usage(format!(
            "native.crate {} has no Cargo.toml",
            app_crate.display()
        )));
    }
    let app_crate = fs::canonicalize(&app_crate).map_err(|source| CliError::Io {
        path: app_crate.clone(),
        source,
    })?;
    let package = package_name(&app_manifest)?;
    let source = squark_source(project_dir, native)?;

    let dir = project_dir.join("target").join("squark-runtime");
    fs::create_dir_all(&dir).map_err(|error| CliError::Io {
        path: dir.clone(),
        source: error,
    })?;
    write_if_changed(
        &dir.join("Cargo.toml"),
        runtime_manifest(
            &source,
            &app_crate,
            &package,
            &native.features,
            native.default_features.unwrap_or(true),
        )
        .as_bytes(),
    )?;
    write_if_changed(&dir.join("main.rs"), RUNTIME_MAIN.as_bytes())?;
    // The checkout pins the toolchain and every dependency version the
    // runtime is tested with; the app's own dependencies join the lockfile.
    for name in ["rust-toolchain.toml", "Cargo.lock"] {
        let target = dir.join(name);
        if name == "Cargo.lock" && target.is_file() {
            continue;
        }
        let bytes = fs::read(source.join(name)).map_err(|error| CliError::Io {
            path: source.join(name),
            source: error,
        })?;
        write_if_changed(&target, &bytes)?;
    }

    let target_dir = dir.join("target");
    eprintln!(
        "squark: building the app runtime with native crate {} ({} profile)",
        package,
        profile.cargo_name()
    );
    let status = Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
        .current_dir(&dir)
        .args(["build", "--profile", profile.cargo_name(), "--manifest-path"])
        .arg(dir.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target_dir)
        // A parent cargo (`cargo run -p squark-cli`) must not pin its own
        // toolchain or target directory onto the nested build.
        .env_remove("RUSTUP_TOOLCHAIN")
        .env_remove("CARGO_TARGET_DIR")
        .status()
        .map_err(|error| CliError::CommandFailed {
            command: "cargo build (app runtime)".to_owned(),
            detail: error.to_string(),
        })?;
    if !status.success() {
        return Err(CliError::CommandFailed {
            command: "cargo build (app runtime)".to_owned(),
            detail: format!("exit status {:?}", status.code()),
        });
    }
    let exe = target_dir
        .join(profile.output_dir())
        .join(format!("squark-app-runtime{}", std::env::consts::EXE_SUFFIX));
    if !exe.is_file() {
        return Err(CliError::Usage(format!(
            "the app runtime build did not produce {}",
            exe.display()
        )));
    }
    Ok(Some(exe))
}

/// Where the shim lives in an app's node_modules (the app installs
/// `@strange-quark/tauri` as a dev dependency), or `SQUARK_TAURI_SHIM`.
fn tauri_shim(project_dir: &Path) -> Result<PathBuf, CliError> {
    if let Some(path) = std::env::var_os("SQUARK_TAURI_SHIM") {
        return Ok(PathBuf::from(path));
    }
    let relative = Path::new("node_modules/@strange-quark/tauri/dist/tauri.classic.js");
    project_dir
        .ancestors()
        .map(|dir| dir.join(relative))
        .find(|path| path.is_file())
        .ok_or_else(|| {
            CliError::Usage(
                "compat.tauri needs @strange-quark/tauri: add it to the app's devDependencies"
                    .to_owned(),
            )
        })
}

/// The classic script that installs `__TAURI_INTERNALS__` before the app runs.
pub fn tauri_prelude(
    project_dir: &Path,
    compat: &RawCompatConfig,
) -> Result<Option<Prelude>, CliError> {
    let Some(tauri) = &compat.tauri else {
        return Ok(None);
    };
    let read = |path: &Path| {
        fs::read(path).map_err(|source| CliError::Io {
            path: path.to_path_buf(),
            source,
        })
    };
    let mut config = serde_json::Map::new();
    if let Some(module) = &tauri.module {
        config.insert("module".into(), module.clone().into());
    }
    let mut source = Vec::new();
    if let Some(fixture) = &tauri.fixture {
        config.insert("fixture".into(), true.into());
        source.extend(read(&resolve_path(project_dir, Path::new(fixture)))?);
        source.push(b'\n');
    }
    let mut prelude = format!(
        "// SPDX-License-Identifier: MIT\nglobalThis.__STRANGE_QUARK_TAURI__ = {};\n",
        serde_json::Value::Object(config)
    )
    .into_bytes();
    prelude.extend(source);
    prelude.extend(read(&tauri_shim(project_dir)?)?);
    Ok(Some(Prelude {
        path: "/__squark/tauri.js".to_owned(),
        source: prelude,
    }))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn package_name_reads_only_the_package_table() {
        let dir = tempfile::tempdir().unwrap();
        let manifest = dir.path().join("Cargo.toml");
        fs::write(
            &manifest,
            "[workspace]\nname = \"no\"\n\n[package]\nversion = \"1.0.0\"\nname = \"demo-native\"\n\n[dependencies]\nname = \"no\"\n",
        )
        .unwrap();
        assert_eq!(package_name(&manifest).unwrap(), "demo-native");
    }

    #[test]
    fn runtime_manifest_links_the_app_crate_against_the_source_checkout() {
        let manifest = runtime_manifest(
            Path::new("/src/sq"),
            Path::new("/app/src-tauri"),
            "demo",
            &["squark".into()],
            false,
        );
        assert!(manifest.contains(r#"squark-host = { path = "/src/sq/crates/squark-host" }"#));
        assert!(manifest.contains(
            r#"app = { path = "/app/src-tauri", package = "demo", features = ["squark"], default-features = false }"#
        ));
        assert!(manifest.contains(r#"stylo = { path = "/src/sq/vendor/stylo" }"#));
        assert!(manifest.contains("[workspace]"));
    }

    #[test]
    fn tauri_prelude_writes_config_fixture_and_shim_in_order() {
        let dir = tempfile::tempdir().unwrap();
        let shim = dir.path().join("node_modules/@strange-quark/tauri/dist");
        fs::create_dir_all(&shim).unwrap();
        fs::write(shim.join("tauri.classic.js"), "/*shim*/").unwrap();
        fs::write(dir.path().join("fixture.js"), "/*fixture*/").unwrap();
        let compat = RawCompatConfig {
            tauri: Some(crate::config::RawTauriCompat {
                module: Some("demo".into()),
                fixture: Some("fixture.js".into()),
            }),
        };
        let prelude = tauri_prelude(dir.path(), &compat).unwrap().unwrap();
        let text = String::from_utf8(prelude.source).unwrap();
        let config = text.find(r#"globalThis.__STRANGE_QUARK_TAURI__ = {"fixture":true,"module":"demo"};"#);
        let fixture = text.find("/*fixture*/");
        let shim = text.find("/*shim*/");
        assert!(config < fixture && fixture < shim, "{text}");
        assert_eq!(prelude.path, "/__squark/tauri.js");
        assert!(tauri_prelude(dir.path(), &RawCompatConfig::default()).unwrap().is_none());
    }
}

#[cfg(test)]
mod prelude_tests {
    use crate::pack::inject_prelude;

    #[test]
    fn the_prelude_runs_before_every_script() {
        assert_eq!(
            inject_prelude(
                "<!doctype html><html><HEAD lang=en><script type=module src=/a.js></script></head></html>",
                "/__squark/tauri.js"
            ),
            "<!doctype html><html><HEAD lang=en><script src=\"/__squark/tauri.js\"></script><script type=module src=/a.js></script></head></html>"
        );
        // <header> is not <head>.
        assert_eq!(
            inject_prelude("<body><header></header><script src=/a.js></script>", "/p.js"),
            "<body><header></header><script src=\"/p.js\"></script><script src=/a.js></script>"
        );
        assert_eq!(inject_prelude("<p>hi</p>", "/p.js"), "<p>hi</p><script src=\"/p.js\"></script>");
    }
}
