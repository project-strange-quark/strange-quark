//! App runtimes for apps with native modules (architecture §13), and the
//! preludes squark.config runs before the app.
//!
//! An app's native modules are an ordinary Rust library crate whose
//! `modules()` returns `Vec<squark_native::Module>`. `squark build` writes a
//! small binary crate under the app's `target/squark-runtime/` that passes
//! them to `squark_host::runtime_main`, builds it from a Strange Quark source
//! checkout, and uses the result as the runtime the pack is appended to.
//! Apps without native modules keep the prebuilt runtime.

use std::{
    fs,
    path::{Component, Path, PathBuf},
    process::Command,
};

use crate::{
    config::{RawNativeConfig, RawPrelude, resolve_path},
    error::CliError,
    pack::Prelude,
};

/// Which Cargo profile builds the app runtime.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RuntimeProfile {
    /// `squark build`: stripped, as the stock dist runtime.
    Dist,
    /// `squark dev`: Strange Quark's dev profile (its dependencies optimized).
    Dev,
}

impl RuntimeProfile {
    fn cargo_name(self) -> &'static str {
        match self {
            Self::Dist => "dist",
            Self::Dev => "dev",
        }
    }

    fn output_dir(self) -> &'static str {
        match self {
            Self::Dist => "dist",
            Self::Dev => "debug",
        }
    }
}

/// The Strange Quark checkout app runtimes build from.
fn squark_source(project_dir: &Path, native: &RawNativeConfig) -> Result<PathBuf, CliError> {
    let source = match (&native.squark_source, std::env::var_os("SQUARK_SOURCE_DIR")) {
        (Some(path), _) => resolve_path(project_dir, Path::new(path)),
        (None, Some(path)) => PathBuf::from(path),
        (None, None) => {
            return Err(CliError::Usage(
                "native.crate needs a Strange Quark source checkout to build the app runtime: set \
                 native.squarkSource in squark.config.ts or SQUARK_SOURCE_DIR"
                    .to_owned(),
            ));
        }
    };
    if !source.join("crates/squark-host/Cargo.toml").is_file() {
        return Err(CliError::Usage(format!(
            "{} is not a Strange Quark source checkout (no crates/squark-host)",
            source.display()
        )));
    }
    fs::canonicalize(&source).map_err(|source_error| CliError::Io {
        path: source,
        source: source_error,
    })
}

/// The `[package] name` of a crate's Cargo.toml.
fn package_name(manifest: &Path) -> Result<String, CliError> {
    let text = fs::read_to_string(manifest).map_err(|source| CliError::Io {
        path: manifest.to_path_buf(),
        source,
    })?;
    let mut in_package = false;
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            in_package = line == "[package]";
            continue;
        }
        if in_package
            && let Some(rest) = line.strip_prefix("name")
            && let Some(value) = rest.trim_start().strip_prefix('=')
        {
            let value = value.trim().trim_matches('"');
            if !value.is_empty() {
                return Ok(value.to_owned());
            }
        }
    }
    Err(CliError::Usage(format!(
        "{} has no [package] name",
        manifest.display()
    )))
}

fn toml_path(path: &Path) -> String {
    path.display()
        .to_string()
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
}

/// The generated runtime crate's manifest.
pub fn runtime_manifest(
    source: &Path,
    app_crate: &Path,
    app_package: &str,
    features: &[String],
    default_features: bool,
) -> String {
    let features = features
        .iter()
        .map(|feature| format!("\"{}\"", feature.replace(['"', '\\'], "")))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        r#"# Generated by `squark build`; do not edit.
[package]
name = "squark-app-runtime"
version = "0.0.0"
edition = "2024"
publish = false

[[bin]]
name = "squark-app-runtime"
path = "main.rs"

[dependencies]
squark-host = {{ path = "{host}" }}
squark-native = {{ path = "{native}" }}
app = {{ path = "{app}", package = "{package}", features = [{features}], default-features = {default_features} }}

[patch.crates-io]
stylo = {{ path = "{stylo}" }}

[profile.release]
lto = "thin"
codegen-units = 1
debug = "line-tables-only"

[profile.dist]
inherits = "release"
debug = false
strip = "symbols"

[profile.dev.package."*"]
opt-level = 2

[workspace]
"#,
        host = toml_path(&source.join("crates/squark-host")),
        native = toml_path(&source.join("crates/squark-native")),
        app = toml_path(app_crate),
        package = app_package.replace('"', ""),
        stylo = toml_path(&source.join("vendor/stylo")),
    )
}

pub const RUNTIME_MAIN: &str = r#"// Generated by `squark build`; do not edit.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

fn main() -> std::process::ExitCode {
    squark_host::runtime_main(Some(squark_native::dispatcher(app::modules())))
}
"#;

fn write_if_changed(path: &Path, contents: &[u8]) -> Result<(), CliError> {
    if fs::read(path).is_ok_and(|current| current == contents) {
        return Ok(());
    }
    fs::write(path, contents).map_err(|source| CliError::Io {
        path: path.to_path_buf(),
        source,
    })
}

/// Build the app runtime for `native.crate`, returning the executable.
/// The `channel` a rust-toolchain.toml pins, if any.
fn toolchain_channel(text: &str) -> Option<String> {
    let mut in_toolchain = false;
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.starts_with('[') {
            in_toolchain = line == "[toolchain]";
            continue;
        }
        if let Some(value) = line.strip_prefix("channel")
            && in_toolchain
            && let Some(value) = value.trim_start().strip_prefix('=')
        {
            let value = value.trim().trim_matches('"').trim_matches('\'');
            return (!value.is_empty()).then(|| value.to_owned());
        }
    }
    None
}

fn nested_cargo(toolchain: Option<&str>) -> Command {
    // Cargo exports its own binary and compiler settings to commands it
    // runs. Start Cargo from PATH so rustup can use the source checkout's
    // toolchain, and build the app runtime with its own settings.
    let mut command = Command::new("cargo");
    for name in [
        "CARGO",
        "CARGO_TARGET_DIR",
        "CARGO_ENCODED_RUSTFLAGS",
        "RUSTC",
        "RUSTC_WRAPPER",
        "RUSTC_WORKSPACE_WRAPPER",
        "RUSTUP_TOOLCHAIN",
    ] {
        command.env_remove(name);
    }
    if let Some(channel) = toolchain {
        command.env("RUSTUP_TOOLCHAIN", channel);
    }
    command
}

pub fn build_native_runtime(
    project_dir: &Path,
    native: &RawNativeConfig,
    profile: RuntimeProfile,
) -> Result<Option<PathBuf>, CliError> {
    let Some(crate_dir) = &native.crate_dir else {
        return Ok(None);
    };
    let app_crate = resolve_path(project_dir, Path::new(crate_dir));
    let app_manifest = app_crate.join("Cargo.toml");
    if !app_manifest.is_file() {
        return Err(CliError::Usage(format!(
            "native.crate {} has no Cargo.toml",
            app_crate.display()
        )));
    }
    let app_crate = fs::canonicalize(&app_crate).map_err(|source| CliError::Io {
        path: app_crate.clone(),
        source,
    })?;
    let package = package_name(&app_manifest)?;
    let source = squark_source(project_dir, native)?;

    let dir = project_dir.join("target").join("squark-runtime");
    fs::create_dir_all(&dir).map_err(|error| CliError::Io {
        path: dir.clone(),
        source: error,
    })?;
    write_if_changed(
        &dir.join("Cargo.toml"),
        runtime_manifest(
            &source,
            &app_crate,
            &package,
            &native.features,
            native.default_features.unwrap_or(true),
        )
        .as_bytes(),
    )?;
    write_if_changed(&dir.join("main.rs"), RUNTIME_MAIN.as_bytes())?;
    // The checkout pins the toolchain and every dependency version the
    // runtime is tested with; the app's own dependencies join the lockfile.
    for name in ["rust-toolchain.toml", "Cargo.lock"] {
        let target = dir.join(name);
        if name == "Cargo.lock" && target.is_file() {
            continue;
        }
        let bytes = fs::read(source.join(name)).map_err(|error| CliError::Io {
            path: source.join(name),
            source: error,
        })?;
        write_if_changed(&target, &bytes)?;
    }

    let target_dir = dir.join("target");
    eprintln!(
        "squark: building the app runtime with native crate {} ({} profile)",
        package,
        profile.cargo_name()
    );
    let toolchain = fs::read_to_string(source.join("rust-toolchain.toml"))
        .ok()
        .and_then(|text| toolchain_channel(&text));
    let status = nested_cargo(toolchain.as_deref())
        .current_dir(&dir)
        .args([
            "build",
            "--profile",
            profile.cargo_name(),
            "--manifest-path",
        ])
        .arg(dir.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target_dir)
        .status()
        .map_err(|error| CliError::CommandFailed {
            command: "cargo build (app runtime)".to_owned(),
            detail: error.to_string(),
        })?;
    if !status.success() {
        return Err(CliError::CommandFailed {
            command: "cargo build (app runtime)".to_owned(),
            detail: format!("exit status {:?}", status.code()),
        });
    }
    let exe = target_dir.join(profile.output_dir()).join(format!(
        "squark-app-runtime{}",
        std::env::consts::EXE_SUFFIX
    ));
    if !exe.is_file() {
        return Err(CliError::Usage(format!(
            "the app runtime build did not produce {}",
            exe.display()
        )));
    }
    Ok(Some(exe))
}

/// A prelude's script file: relative to the project, or inside a package
/// installed in the project's (or an ancestor's) node_modules.
fn prelude_file(project_dir: &Path, file: &str) -> Result<PathBuf, CliError> {
    let path = Path::new(file);
    if path.is_absolute()
        || matches!(
            path.components().next(),
            Some(Component::CurDir | Component::ParentDir)
        )
    {
        return Ok(resolve_path(project_dir, path));
    }
    project_dir
        .ancestors()
        .map(|dir| dir.join("node_modules").join(path))
        .find(|candidate| candidate.is_file())
        .ok_or_else(|| {
            CliError::Usage(format!(
                "prelude {file} was not found in node_modules; install the package that provides it"
            ))
        })
}

/// The `preludes` of squark.config as one classic script, run before the
/// app: each entry's globals, then its file, in order.
pub fn preludes(project_dir: &Path, preludes: &[RawPrelude]) -> Result<Option<Prelude>, CliError> {
    if preludes.is_empty() {
        return Ok(None);
    }
    let mut source = b"// Preludes from squark.config, run before the app's scripts.\n".to_vec();
    for prelude in preludes {
        for (name, value) in &prelude.globals {
            source.extend(
                format!(
                    "globalThis[{}] = {};\n",
                    serde_json::Value::String(name.clone()),
                    value
                )
                .into_bytes(),
            );
        }
        let path = prelude_file(project_dir, &prelude.file)?;
        source.extend(fs::read(&path).map_err(|error| CliError::Io {
            path: path.clone(),
            source: error,
        })?);
        source.push(b'\n');
    }
    Ok(Some(Prelude {
        path: "/__squark/prelude.js".to_owned(),
        source,
    }))
}

#[cfg(test)]
mod tests {
    #[test]
    fn nested_cargo_uses_path_and_discards_parent_compiler_settings() {
        use std::{collections::HashMap, ffi::OsStr};

        let command = nested_cargo(Some("1.98.1"));
        assert_eq!(command.get_program(), "cargo");
        let env: HashMap<_, _> = command.get_envs().collect();
        for name in [
            "CARGO",
            "CARGO_TARGET_DIR",
            "CARGO_ENCODED_RUSTFLAGS",
            "RUSTC",
            "RUSTC_WRAPPER",
            "RUSTC_WORKSPACE_WRAPPER",
        ] {
            assert_eq!(env.get(OsStr::new(name)), Some(&None), "{name}");
        }
        assert_eq!(
            env[OsStr::new("RUSTUP_TOOLCHAIN")],
            Some(OsStr::new("1.98.1"))
        );
        assert!(
            nested_cargo(None)
                .get_envs()
                .any(|(name, value)| { name == "RUSTUP_TOOLCHAIN" && value.is_none() })
        );
    }

    #[test]
    fn the_nested_build_uses_the_checkouts_toolchain_channel() {
        assert_eq!(
            super::toolchain_channel(
                "# pinned\n[toolchain]\nchannel = \"1.98.1\" # see CI\ncomponents = [\"clippy\"]\n"
            )
            .as_deref(),
            Some("1.98.1")
        );
        assert_eq!(super::toolchain_channel("[other]\nchannel = \"x\"\n"), None);
        assert_eq!(super::toolchain_channel(""), None);
        assert!(super::toolchain_channel(include_str!("../../../rust-toolchain.toml")).is_some());
    }

    use super::*;

    #[test]
    fn package_name_reads_only_the_package_table() {
        let dir = tempfile::tempdir().unwrap();
        let manifest = dir.path().join("Cargo.toml");
        fs::write(
            &manifest,
            "[workspace]\nname = \"no\"\n\n[package]\nversion = \"1.0.0\"\nname = \"demo-native\"\n\n[dependencies]\nname = \"no\"\n",
        )
        .unwrap();
        assert_eq!(package_name(&manifest).unwrap(), "demo-native");
    }

    #[test]
    fn runtime_manifest_links_the_app_crate_against_the_source_checkout() {
        let (source, app) = if cfg!(windows) {
            (r"\\?\C:\src\Strange Quark", r"\\?\D:\app\native")
        } else {
            ("/src/Strange Quark", r#"/app/"native""#)
        };
        let source = Path::new(source);
        let manifest = runtime_manifest(source, Path::new(app), "demo", &["squark".into()], false);
        for (dependency, path) in [
            ("squark-host", source.join("crates/squark-host")),
            ("squark-native", source.join("crates/squark-native")),
            ("stylo", source.join("vendor/stylo")),
        ] {
            let path = serde_json::to_string(path.to_str().unwrap()).unwrap();
            assert!(manifest.contains(&format!("{dependency} = {{ path = {path} }}")));
        }
        let app = serde_json::to_string(app).unwrap();
        assert!(manifest.contains(&format!(
            r#"app = {{ path = {app}, package = "demo", features = ["squark"], default-features = false }}"#
        )));
        assert!(manifest.contains("[workspace]"));
    }

    #[test]
    fn preludes_assign_globals_then_run_files_in_order() {
        let dir = tempfile::tempdir().unwrap();
        let package = dir.path().join("node_modules/@acme/shim/dist");
        fs::create_dir_all(&package).unwrap();
        fs::write(package.join("shim.js"), "/*shim*/").unwrap();
        fs::write(dir.path().join("fixture.js"), "/*fixture*/").unwrap();
        let project = dir.path().join("app");
        fs::create_dir_all(&project).unwrap();
        let entries = vec![
            RawPrelude {
                file: "../fixture.js".into(),
                globals: serde_json::Map::new(),
            },
            RawPrelude {
                file: "@acme/shim/dist/shim.js".into(),
                globals: serde_json::json!({ "__ACME__": { "module": "demo" } })
                    .as_object()
                    .unwrap()
                    .clone(),
            },
        ];
        let prelude = preludes(&project, &entries).unwrap().unwrap();
        let text = String::from_utf8(prelude.source).unwrap();
        let fixture = text.find("/*fixture*/").unwrap();
        let global = text
            .find(r#"globalThis["__ACME__"] = {"module":"demo"};"#)
            .unwrap();
        let shim = text.find("/*shim*/").unwrap();
        assert!(fixture < global && global < shim, "{text}");
        assert_eq!(prelude.path, "/__squark/prelude.js");
        assert!(preludes(&project, &[]).unwrap().is_none());
        let missing = RawPrelude {
            file: "@acme/missing.js".into(),
            globals: serde_json::Map::new(),
        };
        assert!(preludes(&project, &[missing]).is_err());
    }

    #[test]
    fn preludes_accept_explicit_relative_paths_with_native_separators() {
        let dir = tempfile::tempdir().unwrap();
        let project = dir.path().join("app");
        fs::create_dir(&project).unwrap();
        fs::write(project.join("local.js"), "/*local*/").unwrap();
        fs::write(dir.path().join("shared.js"), "/*shared*/").unwrap();
        let files = if cfg!(windows) {
            [r".\local.js", r"..\shared.js"]
        } else {
            ["./local.js", "../shared.js"]
        };
        let entries = files.map(|file| RawPrelude {
            file: file.into(),
            globals: serde_json::Map::new(),
        });
        let prelude = preludes(&project, &entries).unwrap().unwrap();
        let text = String::from_utf8(prelude.source).unwrap();
        assert!(text.contains("/*local*/"));
        assert!(text.contains("/*shared*/"));
    }
}

#[cfg(test)]
mod prelude_tests {
    use crate::pack::inject_prelude;

    #[test]
    fn the_prelude_runs_before_every_script() {
        assert_eq!(
            inject_prelude(
                "<!doctype html><html><HEAD lang=en><script type=module src=/a.js></script></head></html>",
                "/__squark/prelude.js"
            ),
            "<!doctype html><html><HEAD lang=en><script src=\"/__squark/prelude.js\"></script><script type=module src=/a.js></script></head></html>"
        );
        // <header> is not <head>.
        assert_eq!(
            inject_prelude(
                "<body><header></header><script src=/a.js></script>",
                "/p.js"
            ),
            "<body><header></header><script src=\"/p.js\"></script><script src=/a.js></script>"
        );
        assert_eq!(
            inject_prelude("<p>hi</p>", "/p.js"),
            "<p>hi</p><script src=\"/p.js\"></script>"
        );
    }
}
