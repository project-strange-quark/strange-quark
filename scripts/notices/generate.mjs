#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// Writes THIRD_PARTY_NOTICES.txt, the licences of the third-party software
// linked into the shipped squark and squark-runtime binaries:
//   1. the libraries in V8's prebuilt static library, from
//      scripts/notices/v8/components.json and the licence texts beside it;
//   2. the Rust crates, from cargo-about with scripts/notices/about.toml.
// See scripts/notices/README.md.
//
// Usage: node scripts/notices/generate.mjs [--check]
//   --check  exit 1 if THIRD_PARTY_NOTICES.txt is out of date, without writing it.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../..");
export const NOTICES_PATH = path.join(repoRoot, "THIRD_PARTY_NOTICES.txt");
// The version whose output is committed; others may order or word it differently.
const CARGO_ABOUT_VERSION = "0.9.3";
const RULE = "=".repeat(80);
const THIN_RULE = "-".repeat(80);

/** The version of `name` that Cargo.lock resolves. */
function lockedVersion(name) {
  const lock = fs.readFileSync(path.join(repoRoot, "Cargo.lock"), "utf8");
  const match = lock.match(new RegExp(`\\[\\[package\\]\\]\\nname = "${name}"\\nversion = "([^"]+)"`));
  if (!match) throw new Error(`Cargo.lock has no package ${name}`);
  return match[1];
}

function v8Section() {
  const manifest = JSON.parse(fs.readFileSync(path.join(here, "v8/components.json"), "utf8"));
  const locked = lockedVersion("v8");
  if (manifest.v8Crate !== locked) {
    throw new Error(
      `scripts/notices/v8 describes the v8 crate ${manifest.v8Crate}, but Cargo.lock has ${locked}. ` +
        "Update the components and licence texts for the new V8 first (scripts/notices/README.md).",
    );
  }
  const entries = manifest.components.map((component) => {
    const texts = component.files.map((file) =>
      fs.readFileSync(path.join(here, "v8", file), "utf8").replace(/\r\n/g, "\n").trimEnd(),
    );
    return [
      RULE,
      `${component.name} ${component.version}`,
      `Licence: ${component.license}`,
      `Source: ${component.source}`,
      THIN_RULE,
      "",
      texts.join(`\n\n${THIN_RULE}\n\n`),
      "",
    ].join("\n");
  });
  return [
    `Part 1: libraries bundled in V8's prebuilt static library (v8 crate ${locked})`,
    "",
    ...entries,
  ].join("\n");
}

function rustSection() {
  const version = execFileSync("cargo", ["about", "--version"], { encoding: "utf8" }).trim();
  if (version !== `cargo-about ${CARGO_ABOUT_VERSION}`) {
    throw new Error(
      `found ${version}; install cargo-about ${CARGO_ABOUT_VERSION} with ` +
        `cargo install cargo-about --locked --features cli --version ${CARGO_ABOUT_VERSION}`,
    );
  }
  // cargo-about runs offline, so its output never depends on a network lookup;
  // fetch the locked crates first so a clean checkout has them.
  execFileSync("cargo", ["fetch", "--locked"], { cwd: repoRoot, stdio: ["ignore", "ignore", "inherit"] });
  const text = execFileSync(
    "cargo",
    [
      "about",
      "generate",
      "--locked",
      "--offline",
      "--fail",
      "--workspace",
      "-c",
      path.join(here, "about.toml"),
      path.join(here, "notices.hbs"),
    ],
    { cwd: repoRoot, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] },
  );
  return ["Part 2: Rust crates", "", text.replace(/\r\n/g, "\n").trim(), ""].join("\n");
}

export function renderNotices() {
  return [
    "Third-party software in Strange Quark",
    "",
    "The squark CLI, the squark-runtime binary and every app that `squark build`",
    "makes from the runtime include the software listed below. Each entry names",
    "the licence it is used under, followed by the licence text. Print this file",
    "from a runtime or a built app with `--third-party-notices`.",
    "",
    "This file is generated by scripts/notices/generate.mjs. Do not edit it.",
    "",
    v8Section(),
    rustSection(),
  ].join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  try {
    const check = process.argv.includes("--check");
    const notices = renderNotices();
    if (check) {
      const current = fs.existsSync(NOTICES_PATH) ? fs.readFileSync(NOTICES_PATH, "utf8") : null;
      if (current !== notices) {
        console.error(
          "THIRD_PARTY_NOTICES.txt is out of date; run node scripts/notices/generate.mjs and commit the result.",
        );
        process.exit(1);
      }
      console.log("THIRD_PARTY_NOTICES.txt is up to date.");
    } else {
      fs.writeFileSync(NOTICES_PATH, notices);
      console.log(`wrote ${path.relative(repoRoot, NOTICES_PATH)} (${notices.length} bytes)`);
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
